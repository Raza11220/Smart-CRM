import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { mkdir, writeFile } from 'node:fs/promises'
const { chromium } = await import(pathToFileURL(process.env.SMARTCRM_PLAYWRIGHT_PATH).href)
const browser = await chromium.launch({ headless: true, executablePath: process.env.SMARTCRM_CHROMIUM_PATH })
const base = process.env.SMARTCRM_URL || 'http://127.0.0.1:5173'
const checks = [], errors = []
const check = message => { checks.push(message); console.log(`PASS ${message}`) }
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, timezoneId: 'America/Los_Angeles', reducedMotion: 'reduce' })
const page = await context.newPage()
page.on('pageerror', error => errors.push(error.message))
const db = () => page.evaluate(() => JSON.parse(localStorage.getItem('smartcrm-data-v2')).data)
async function go(route) { await page.goto(base + route); await page.locator('h1').first().waitFor() }
await mkdir('artifacts/pakistan', { recursive: true })
try {
  await go('/dashboard')
  const data = await db()
  const preferences = await page.evaluate(() => JSON.parse(localStorage.getItem('smartcrm-preferences-v1') || 'null'))
  // Zustand saves defaults on the first preference mutation, not on a read-only visit.
  if (preferences) assert.equal(preferences.state.preferences.currency, 'PKR')
  const won = data.deals.filter(d => d.stage === 'Won')
  const revenue = won.reduce((sum, d) => sum + d.value, 0)
  const pipeline = data.deals.filter(d => !['Won', 'Lost'].includes(d.stage)).reduce((sum, d) => sum + d.value, 0)
  const total = await page.locator('.metric-card').first().locator('strong').innerText()
  assert.equal(total, `Rs. ${revenue.toLocaleString('en-PK')}`)
  assert.equal(await page.locator('.overview-strip>div').nth(0).locator('strong').evaluate(node => node.firstChild.textContent), '40')
  assert.equal(await page.locator('.overview-strip>div').nth(1).locator('strong').evaluate(node => node.firstChild.textContent), String(data.tasks.filter(t => t.status !== 'Completed').length))
  assert.ok((await page.locator('.overview-strip>div').nth(2).innerText()).includes(`Rs. ${pipeline.toLocaleString('en-PK')}`))
  for (const route of ['/dashboard', '/customers', '/leads', '/pipeline', '/tasks', '/team', '/reports']) {
    await go(route)
    const text = await page.locator('main').innerText()
    assert.ok(!/Alex Morgan|Sarah Johnson|Acme Inc\.|San Francisco|\$\d/.test(text), `${route} contains old seeded content`)
    if (['/dashboard', '/customers', '/leads', '/pipeline', '/tasks'].includes(route)) assert.ok(/Lahore|Karachi|Islamabad|PakGrowth|NexaSoft|Punjab|BluePeak|Crescent|Falcon|PakVista/.test(text), `${route} lacks Pakistani company data`)
    if (route === '/team') { assert.equal(await page.locator('.employee-card').count(), 12); assert.ok(text.includes('Business Development Officer')); assert.ok(text.includes('CRM Administrator')) }
    if (['/dashboard', '/leads', '/pipeline', '/team', '/reports'].includes(route)) assert.ok(text.includes('Rs.'), `${route} lacks PKR formatting`)
    await page.screenshot({ path: `artifacts/pakistan/${route.slice(1)}-desktop.png` })
  }
  check('Dashboard totals and all seven CRM modules display the connected Pakistani records and Rs. amounts')
  await go('/customers/customer-1')
  assert.ok((await page.locator('main').innerText()).includes('Lahore, Punjab, Pakistan'))
  assert.ok((await page.locator('main').innerText()).includes('Muhammad Ahmed'))
  assert.ok((await page.locator('main').innerText()).includes('.example'))
  check('Customer details show fictional contacts and a Pakistani postal address')
  await go('/settings')
  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  assert.equal(await page.getByRole('combobox', { name: 'Display currency' }).inputValue(), 'PKR')
  assert.equal(await page.getByRole('combobox', { name: 'Date format' }).inputValue(), 'dd MMM yyyy')
  await page.getByText('Asia/Karachi', { exact: true }).waitFor()
  await page.getByText('Professional English · en-PK', { exact: true }).waitFor()
  await page.getByText('Pakistan Standard Time (PST, UTC+05:00)', { exact: true }).waitFor()
  check('Default currency, date format, locale, and timezone are localized')
  await page.setViewportSize({ width: 390, height: 844 })
  for (const route of ['/dashboard', '/leads', '/pipeline', '/team', '/reports']) {
    await go(route)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    assert.equal(overflow, false, `${route} overflows with larger PKR amounts`)
    await page.screenshot({ path: `artifacts/pakistan/${route.slice(1)}-mobile.png` })
  }
  check('Larger PKR values fit the existing mobile layouts')

  const legacyContext = await browser.newContext({ viewport: { width: 1440, height: 960 } })
  const legacy = { customers: [{ ...data.customers[0], name: 'Preserved Legacy Contact', company: 'Legacy Account', notes: 'DO NOT LOSE THIS USER EDIT' }], leads: [], deals: [], tasks: [], employees: [{ ...data.employees[0], name: 'Legacy Owner', email: 'admin@smartcrm.demo' }, { ...data.employees[1], email: 'staff@smartcrm.demo' }], activities: [] }
  const raw = JSON.stringify(legacy)
  const noPreferencesContext = await browser.newContext()
  await noPreferencesContext.addInitScript(({ raw }) => {
    if (!localStorage.getItem('smartcrm-data-v1')) localStorage.setItem('smartcrm-data-v1', raw)
  }, { raw })
  const noPreferencesPage = await noPreferencesContext.newPage()
  noPreferencesPage.on('pageerror', error => errors.push(error.message))
  await noPreferencesPage.goto(`${base}/settings`)
  await noPreferencesPage.getByRole('button', { name: 'Preferences', exact: true }).click()
  assert.equal(await noPreferencesPage.getByRole('combobox', { name: 'Display currency' }).inputValue(), 'USD')
  assert.equal(await noPreferencesPage.evaluate(() => localStorage.getItem('smartcrm-data-v2')), null)
  await noPreferencesContext.close()
  check('Legacy values keep their original currency even when no preference record was ever saved')
  await legacyContext.addInitScript(({ raw }) => {
    if (localStorage.getItem('migration-test-initialized')) return
    localStorage.setItem('migration-test-initialized', 'yes')
    localStorage.setItem('smartcrm-data-v1', raw)
    localStorage.setItem('unrelated-storage-key', 'KEEP ME')
    localStorage.setItem('smartcrm-preferences-v1', JSON.stringify({ state: { preferences: { theme: 'dark', currency: 'USD', dateFormat: 'MM/dd/yyyy', collapsed: true } }, version: 0 }))
  }, { raw })
  const migrationPage = await legacyContext.newPage()
  migrationPage.on('pageerror', error => errors.push(error.message))
  await migrationPage.goto(`${base}/customers`)
  await migrationPage.getByRole('heading', { name: 'Customers', exact: true }).waitFor()
  await migrationPage.getByText('Preserved Legacy Contact', { exact: true }).waitFor()
  assert.equal(await migrationPage.evaluate(() => localStorage.getItem('smartcrm-data-v2')), null)
  await migrationPage.goto(`${base}/settings`)
  await migrationPage.getByRole('button', { name: 'Preferences', exact: true }).click()
  assert.equal(await migrationPage.getByRole('combobox', { name: 'Display currency' }).inputValue(), 'USD')
  assert.equal(await migrationPage.getByRole('combobox', { name: 'Date format' }).inputValue(), 'MM/dd/yyyy')
  await migrationPage.getByRole('button', { name: 'Account', exact: true }).click()
  await migrationPage.getByText('Previous demo records are preserved.', { exact: false }).waitFor()
  await migrationPage.getByRole('button', { name: 'Reset Demo Data', exact: true }).click()
  await migrationPage.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await migrationPage.evaluate(() => localStorage.getItem('smartcrm-data-v1')), raw)
  assert.equal(await migrationPage.evaluate(() => localStorage.getItem('smartcrm-data-v2')), null)
  check('Legacy workspace stays intact; cancelling Reset Demo Data does not write or mix Pakistani records')
  await migrationPage.getByRole('button', { name: 'Reset Demo Data', exact: true }).click()
  await migrationPage.getByRole('dialog').getByRole('button', { name: 'Reset Demo Data', exact: true }).click()
  await migrationPage.getByRole('dialog').waitFor({ state: 'hidden' })
  const persisted = await migrationPage.evaluate(() => ({ old: localStorage.getItem('smartcrm-data-v1'), current: JSON.parse(localStorage.getItem('smartcrm-data-v2')), backup: JSON.parse(localStorage.getItem('smartcrm-data-before-pakistan-reset')), unrelated: localStorage.getItem('unrelated-storage-key'), preferences: JSON.parse(localStorage.getItem('smartcrm-preferences-v1')).state.preferences }))
  assert.equal(persisted.old, raw)
  assert.equal(persisted.backup.raw, raw)
  assert.equal(persisted.unrelated, 'KEEP ME')
  assert.equal(persisted.current.seedVersion, 2)
  assert.equal(persisted.current.data.customers.length, 40)
  assert.equal(persisted.current.data.employees[0].name, 'Ahmed Faraz')
  assert.equal(persisted.preferences.currency, 'PKR')
  assert.equal(persisted.preferences.locale, 'en-PK')
  assert.equal(persisted.preferences.timezone, 'Asia/Karachi')
  assert.equal(persisted.preferences.dateFormat, 'dd MMM yyyy')
  assert.equal(persisted.preferences.theme, 'dark')
  assert.equal(persisted.preferences.collapsed, true)
  await migrationPage.reload()
  await migrationPage.locator('h1').waitFor()
  assert.equal(await migrationPage.evaluate(() => JSON.parse(localStorage.getItem('smartcrm-data-v2')).data.customers.length), 40)
  check('Confirmed reset installs only the Pakistani seed, preserves a backup and unrelated keys, and safely migrates regional preferences')
  await legacyContext.close()
  assert.deepEqual(errors, [])
  await writeFile('artifacts/pakistan/ui-results.json', JSON.stringify({ passed: checks, errors }, null, 2))
  console.log(`${checks.length} Pakistan integration and migration UI checks passed.`)
} catch (error) { await page.screenshot({ path: 'artifacts/pakistan/failure.png', fullPage: true }); console.error(error); process.exitCode = 1 }
finally { await browser.close() }
