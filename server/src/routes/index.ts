import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import { authenticate, adminOnly, cookieRequest } from '../middleware/auth.middleware';
import { validate } from '../utils/http';
import * as auth from '../controllers/auth.controller';
import * as users from '../controllers/user.controller';
import * as events from '../controllers/event.controller';
import { recordController } from '../controllers/record.controller';
import { analyticsController } from '../controllers/analytics.controller';
import * as schemas from '../validators/schemas';
import type { Kind } from '../models/crm.models';
export const routes = Router();
const authRoutes = Router();
const loginLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 15, skipSuccessfulRequests: true, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many sign-in attempts. Try again later.' } });
const registrationLimit = rateLimit({ windowMs: 60 * 60 * 1000, limit: 10, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many registration requests' } });
authRoutes.post('/register', registrationLimit, cookieRequest, validate(schemas.registerSchema), auth.register);
authRoutes.post('/login', loginLimit, cookieRequest, validate(schemas.loginSchema), auth.login);
authRoutes.post('/refresh', cookieRequest, validate(schemas.preferencesSchema.pick({})), auth.refresh);
authRoutes.post('/logout', cookieRequest, auth.logout);
authRoutes.get('/me', authenticate, auth.me);
authRoutes.patch('/profile', authenticate, validate(schemas.profileSchema), auth.profile);
authRoutes.patch('/preferences', authenticate, validate(schemas.preferencesSchema), auth.preferences);
routes.use('/auth', authRoutes);
routes.use(authenticate);
routes.get('/activities', events.activities);
routes.get('/notifications', events.notifications);
routes.patch('/notifications/read-all', events.readAll);
routes.patch('/notifications/:id/read', validate(schemas.idParams, 'params'), events.readNotification);
const userRoutes = Router();
userRoutes.get('/', users.list); userRoutes.post('/', adminOnly, validate(schemas.userCreate), users.create);
userRoutes.get('/:id/performance', validate(schemas.idParams, 'params'), users.performance);
userRoutes.get('/:id', validate(schemas.idParams, 'params'), users.get);
userRoutes.patch('/:id/status', adminOnly, validate(schemas.idParams, 'params'), validate(schemas.userStatus), users.update);
userRoutes.patch('/:id', adminOnly, validate(schemas.idParams, 'params'), validate(schemas.userPatch), users.update);
userRoutes.delete('/:id', adminOnly, validate(schemas.idParams, 'params'), users.remove);
routes.use('/users', userRoutes);
for (const kind of ['customers', 'leads', 'deals', 'tasks'] as Kind[]) {
  const router = Router(); const controller = recordController(kind);
  if (kind === 'deals') router.get('/pipeline', analyticsController('pipeline'));
  router.get('/', controller.list); router.post('/', validate(schemas.createSchemas[kind]), controller.create);
  router.get('/:id', validate(schemas.idParams, 'params'), controller.get);
  if (kind === 'deals') router.patch('/:id/stage', validate(schemas.idParams, 'params'), validate(schemas.stageSchema), controller.update);
  if (kind === 'leads') router.patch('/:id/status', validate(schemas.idParams, 'params'), validate(schemas.leadStatusSchema), controller.update);
  if (kind === 'tasks') router.patch('/:id/status', validate(schemas.idParams, 'params'), validate(schemas.taskStatusSchema), controller.update);
  router.patch('/:id', validate(schemas.idParams, 'params'), validate(schemas.patchSchemas[kind]), controller.update);
  router.delete('/:id', adminOnly, validate(schemas.idParams, 'params'), controller.remove);
  routes.use(`/${kind}`, router);
}
const dashboard = Router();
dashboard.get('/summary', analyticsController('summary')); dashboard.get('/revenue', analyticsController('revenue')); dashboard.get('/sales-performance', analyticsController('salesByEmployee')); dashboard.get('/lead-sources', analyticsController('leadSources')); dashboard.get('/pipeline', analyticsController('pipeline')); dashboard.get('/recent-activities', events.activities); dashboard.get('/top-performers', analyticsController('topPerformers')); dashboard.get('/overview', analyticsController());
routes.use('/dashboard', dashboard);
const reports = Router();
reports.get('/overview', analyticsController()); reports.get('/revenue', analyticsController('revenue')); reports.get('/sales-by-employee', analyticsController('salesByEmployee')); reports.get('/lead-conversion', analyticsController('funnel')); reports.get('/won-lost', analyticsController('wonLost')); reports.get('/lead-sources', analyticsController('leadSources')); reports.get('/pipeline', analyticsController('periodPipeline')); reports.get('/task-performance', analyticsController('taskPerformance'));
routes.use('/reports', reports);
